import type { Brief as BriefT, Status } from '../api/types';
import clsx from '../lib/clsx';
import { parseBrief } from '../lib/briefText';
import { fmtAge, oddsStatus } from '../theme/status';

// A separate, dense layout for paper: tables instead of cards, every mission of the unit, each unmet requirement
// with what drives it, the ranked fixes with their concrete steps, data warnings and sources. Marking and page
// numbers come from the @page rules in styles/index.css; styling from the .pb rules there.

const ST_WORD: Record<Status, string> = { ready: 'READY', watch: 'WATCH', risk: 'AT RISK', unknown: 'UNKNOWN' };
const pc = (p: number) => (Number.isFinite(p) ? `${Math.round(p * 100)}%` : '?');

/** "src:{json}" citation id -> "file loc". */
function sourceLoc(id: string): string {
  try {
    const s = JSON.parse(decodeURIComponent(id.replace(/^src:/, '')));
    return [s.file, s.loc].filter(Boolean).join(' ');
  } catch {
    return '';
  }
}

const stripCites = (text: string) => text.replace(/\s*\[\d+\]/g, '').trim();
const citeNums = (text: string) => [...text.matchAll(/\[(\d+)\]/g)].map((m) => m[1]).join(', ');

export function PrintBrief({ brief, focusId }: { brief: BriefT; focusId: string }) {
  const det = brief.detail;
  const raw = brief.sections.flatMap((s) => s.paragraphs.map((p) => p.text)).join('\n\n');
  const doc = parseBrief(raw);
  const outlook = doc.sections.find((s) => s.key === 'BOTTOM LINE');
  const warnings = doc.sections.find((s) => s.key === 'DATA WARNINGS')?.items ?? [];

  // Plan verdicts only exist in the backend text ("Planned across the event window (on stated ETAs): MAKE, 12.2 days margin").
  const planRe = /^(.*?) \(.*\): [A-Z]+, \d+% across interval; \d+% at start\.\s*Planned across the event window \(on stated ETAs\): ([A-Z]+)(?:, ([\d.]+) days margin)?/;
  const plans = new Map<string, { plan: string; margin: string | null }>();
  for (const it of outlook?.items ?? []) {
    const m = planRe.exec(it.text);
    if (m) plans.set(m[1].replace(/^Support /, '').toUpperCase(), { plan: m[2], margin: m[3] ?? null });
  }
  const planOf = (code: string) => plans.get(code.replace(/^PIER SUPPORT: /, '').toUpperCase());
  const planText = (code: string) => {
    const p = planOf(code);
    return p ? `${p.plan === 'MAKE' ? 'Makes it' : p.plan.charAt(0) + p.plan.slice(1).toLowerCase()}${p.margin ? `, ${p.margin} d margin` : ''}` : null;
  };

  const missions = det?.missions ?? [];
  const fixes = det?.fixes ?? [];
  const worst = [...missions].sort((a, b) => a.pInterval - b.pInterval)[0];
  const focus = missions.find((m) => m.id === focusId) ?? worst;
  let n = 0;
  const sec = () => ++n;

  return (
    <article className="pb">
      {/* masthead */}
      <table style={{ marginBottom: '5pt' }}>
        <tbody>
          <tr>
            <td style={{ border: 0, padding: 0 }}>
              <div className="muted" style={{ fontSize: '7.5pt', fontWeight: 600, letterSpacing: '0.06em', textTransform: 'uppercase' }}>
                Commanding Officer&apos;s readiness brief
              </div>
              <h1>{brief.unit}</h1>
              <div className="muted">
                As of {det?.asOf ?? brief.generatedAt} · {det?.runs ? `${det.runs} simulated runs` : 'simulation'}
                {det?.seed ? `, seed ${det.seed}` : ''} · Generated by LOCKER: read-only analysis, the captain decides
              </div>
            </td>
            {focus && (
              <td style={{ border: 0, padding: 0, width: '1.9in' }}>
                <div className="box" style={{ textAlign: 'right' }}>
                  <div className={`st-${focus.status}`} style={{ fontSize: '8pt' }}>
                    {focus.code} · {ST_WORD[focus.status]}
                  </div>
                  <div className="tn" style={{ fontSize: '20pt', fontWeight: 700, lineHeight: 1.05 }}>
                    {pc(focus.pInterval)}
                  </div>
                  <div className="muted" style={{ fontSize: '7pt' }}>
                    odds across the event · {pc(focus.pStart)} at start
                  </div>
                </div>
              </td>
            )}
          </tr>
        </tbody>
      </table>

      {/* bottom line */}
      <h2>{sec()}. Bottom line up front</h2>
      <ul className="bl">
        {missions.map((m) => {
          const plan = planText(m.code);
          const top = fixes.find((f) => f.effects.some((e) => e.code === m.code));
          const eff = top?.effects.find((e) => e.code === m.code);
          return (
            <li key={m.id}>
              <b>{m.code}</b> ({m.name}, {m.startDtg}): <span className={`st-${m.status}`}>{ST_WORD[m.status]}</span>, <span className="tn">{pc(m.pInterval)}</span> across the
              event, <span className="tn">{pc(m.pStart)}</span> at start{plan ? <span className="tn">; plan: {plan.toLowerCase()}</span> : null}.
              {m.nextDomino && <> Limiting: {m.nextDomino}.</>}
              {top && eff && (
                <>
                  {' '}
                  Best fix: {top.title} (<span className="tn">
                    {pc(eff.before)} → {pc(eff.after)}
                  </span>
                  ).
                </>
              )}
              {m.consequence && <span className="muted"> If missed: {m.consequence}.</span>}
            </li>
          );
        })}
      </ul>

      {/* outlook */}
      <h2>{sec()}. Mission outlook</h2>
      <table>
        <thead>
          <tr>
            <th>Mission</th>
            <th>Event</th>
            <th>Window (Z)</th>
            <th>Status</th>
            <th className="r">Across event</th>
            <th className="r">At start</th>
            <th>Plan (stated ETAs)</th>
            <th>Limiting requirement</th>
          </tr>
        </thead>
        <tbody>
          {missions.map((m) => (
            <tr key={m.id}>
              <td style={{ fontWeight: 700 }}>{m.code}</td>
              <td>{m.name}</td>
              <td className="tn">
                {m.startDtg}
                {m.endDtg ? ` – ${m.endDtg}` : ''}
              </td>
              <td className={`st-${m.status}`}>{ST_WORD[m.status]}</td>
              <td className="r tn" style={{ fontWeight: 700 }}>
                {pc(m.pInterval)}
              </td>
              <td className="r tn">{pc(m.pStart)}</td>
              <td className="tn">{planText(m.code) ?? '—'}</td>
              <td>{m.nextDomino ?? '—'}</td>
            </tr>
          ))}
        </tbody>
      </table>
      <p className="muted" style={{ margin: '2pt 0 0', fontSize: '7.4pt' }}>
        Odds are sampled every six hours across each event window plus known boundaries; not a continuous guarantee. The plan verdict assumes stated part ETAs and the
        current schedule.
      </p>

      {/* requirements */}
      <h2>{sec()}. Requirements not fully met</h2>
      {missions.map((m) => (
        <div key={m.id}>
          <h3>
            {m.code}{' '}
            <span className="muted" style={{ fontWeight: 400 }}>
              · {m.requirements.length} below 100%, {m.metCount} fully met
            </span>
          </h3>
          {m.requirements.length === 0 ? (
            <p className="muted" style={{ margin: 0 }}>
              All requirements met across the event window.
            </p>
          ) : (
            <table>
              <thead>
                <tr>
                  <th style={{ width: '26%' }}>Requirement</th>
                  <th className="r" style={{ width: '6%' }}>
                    Met
                  </th>
                  <th className="r" style={{ width: '8%' }}>
                    If certain
                  </th>
                  <th>What drives it</th>
                  <th style={{ width: '22%' }}>Record</th>
                </tr>
              </thead>
              <tbody>
                {m.requirements.map((r) => (
                  <tr key={r.label}>
                    <td style={{ fontWeight: 600 }}>{r.label}</td>
                    <td className={`r tn st-${oddsStatus(r.p)}`}>{pc(r.p)}</td>
                    <td className="r tn">{r.gain >= 0.005 ? `+${Math.round(r.gain * 100)} pts` : '—'}</td>
                    <td>
                      {r.drivers.length === 0 ? (
                        <span className="muted">Prerequisite event: met when that event is ready (see its own requirements)</span>
                      ) : (
                        r.drivers.map((d, i) => (
                          <div key={i}>
                            {d.title}
                            {d.detail && <span className="muted"> ({d.detail})</span>}
                          </div>
                        ))
                      )}
                    </td>
                    <td className="mono">
                      {r.drivers.map((d, i) => (
                        <div key={i}>{d.source ?? '—'}</div>
                      ))}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          )}
        </div>
      ))}

      {/* fixes */}
      <h2>{sec()}. Ranked fixes (for decision)</h2>
      {fixes.length === 0 ? (
        <p className="muted" style={{ margin: 0 }}>
          No option raises any event by a point or more.
        </p>
      ) : (
        <table>
          <thead>
            <tr>
              <th style={{ width: '3%' }}>#</th>
              <th style={{ width: '27%' }}>Action</th>
              <th>Steps and basis</th>
              <th style={{ width: '17%' }}>Effect</th>
              <th style={{ width: '21%' }}>Other units</th>
            </tr>
          </thead>
          <tbody>
            {fixes.map((f) => (
              <tr key={f.rank}>
                <td className="tn" style={{ fontWeight: 700 }}>
                  {f.rank}
                </td>
                <td style={{ fontWeight: 600 }}>{f.title}</td>
                <td>
                  {f.steps.map((s, i) => (
                    <div key={i}>{s}</div>
                  ))}
                  {f.why.length > 0 && <div className="muted">Basis: {f.why.join('; ')}</div>}
                </td>
                <td className="tn">
                  {f.effects.length
                    ? f.effects.map((e) => (
                        <div key={e.code}>
                          {e.code} {pc(e.before)} → <b>{pc(e.after)}</b>
                        </div>
                      ))
                    : '—'}
                </td>
                <td className="muted">{f.others}</td>
              </tr>
            ))}
          </tbody>
        </table>
      )}
      <p className="muted" style={{ margin: '2pt 0 0', fontSize: '7.4pt' }}>
        Nothing changes until approved in LOCKER (Fixes tab). Approvals are logged; ship records stay read-only.
      </p>

      {/* warnings */}
      {warnings.length > 0 && (
        <>
          <h2>{sec()}. Data warnings</h2>
          <table>
            <thead>
              <tr>
                <th style={{ width: '6%' }}>Code</th>
                <th>Finding</th>
                <th style={{ width: '12%' }}>Sources</th>
              </tr>
            </thead>
            <tbody>
              {warnings.map((w, i) => {
                const m = /^([A-Z]\d+): (.*)$/.exec(w.text);
                return (
                  <tr key={i}>
                    <td className="tn" style={{ fontWeight: 700 }}>
                      {m?.[1] ?? '—'}
                    </td>
                    <td>{stripCites(m ? m[2] : w.text)}</td>
                    <td className="tn">{citeNums(w.text) || '—'}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </>
      )}

      {/* sources */}
      <h2>{sec()}. Sources cited</h2>
      <table>
        <thead>
          <tr>
            <th style={{ width: '3%' }}>#</th>
            <th style={{ width: '29%' }}>System of record</th>
            <th>Record</th>
            <th style={{ width: '31%' }}>Location</th>
            <th style={{ width: '10%' }}>Age</th>
          </tr>
        </thead>
        <tbody>
          {brief.citations.map((c, i) => (
            <tr key={c.id}>
              <td className="tn">{i + 1}</td>
              <td>{c.system}</td>
              <td>{c.title}</td>
              <td className="mono">{sourceLoc(c.id)}</td>
              <td className={clsx('tn', c.stale && 'st-watch')}>
                {fmtAge(c.ageHours).replace(' old', '')}
                {c.stale ? ' STALE' : ''}
              </td>
            </tr>
          ))}
        </tbody>
      </table>

      <p className="muted" style={{ margin: '6pt 0 0', fontSize: '7.4pt' }}>
        {doc.disclaimer.join(' ')} Synthetic exercise data: facilities, failures and personnel are invented.
      </p>
    </article>
  );
}
